#!/usr/bin/env python3
"""Convert the prompt WAV files (16 kHz, mono, 16-bit) into IMA ADPCM C arrays.

    python3 wav2c.py --wav wav --out ../../proj_cm55/audio

For every id in prompts.csv, <wav>/<id>.wav is
  1. trimmed (leading / trailing samples 40 dB below the clip peak),
  2. peak normalized to -3 dBFS and padded with 15 ms of silence each side,
  3. encoded as 4-bit IMA ADPCM (4:1, 8 kB per second at 16 kHz),
and written to audio_clips.c / audio_clips.h (enum audio_clip_id_t).
Stream format: low nibble first, decoder starts at predictor 0, index 0.
Standard library only (no numpy).
"""
import argparse
import array
import os
import sys
import wave

from prompts import load_prompts

RATE = 16000
PAD = int(0.015 * RATE)
TRIM_DB = -40.0  # relative to the clip peak
PEAK = int(32767 * 10 ** (-3 / 20))

STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41,
        45, 50, 55, 60, 66, 73, 80, 88, 97, 107, 118, 130, 143, 157, 173, 190, 209,
        230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658, 724, 796, 876,
        963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024,
        3327, 3660, 4026, 4428, 4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493,
        10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623, 27086,
        29794, 32767]
INDEX = [-1, -1, -1, -1, 2, 4, 6, 8]


def ima_encode(samples):
    pred, idx, out, nib = 0, 0, bytearray(), []
    for s in samples:
        step = STEP[idx]
        diff = s - pred
        code = 0
        if diff < 0:
            code, diff = 8, -diff
        dq = step >> 3
        if diff >= step:
            code |= 4; diff -= step; dq += step
        step >>= 1
        if diff >= step:
            code |= 2; diff -= step; dq += step
        step >>= 1
        if diff >= step:
            code |= 1; dq += step
        pred = pred - dq if code & 8 else pred + dq
        pred = max(-32768, min(32767, pred))
        idx = max(0, min(88, idx + INDEX[code & 7]))
        nib.append(code)
    if len(nib) & 1:
        nib.append(0)
    for i in range(0, len(nib), 2):
        out.append(nib[i] | (nib[i + 1] << 4))
    return bytes(out)


def load_wav(path):
    with wave.open(path, "rb") as w:
        if (w.getnchannels(), w.getsampwidth(), w.getframerate()) != (1, 2, RATE):
            raise SystemExit(f"{path}: need 16 kHz mono 16-bit")
        pcm = array.array("h", w.readframes(w.getnframes()))
    if sys.byteorder == "big":
        pcm.byteswap()
    return list(pcm)


def prepare(pcm):
    level = max(abs(s) for s in pcm) * 10 ** (TRIM_DB / 20)
    loud = [i for i, s in enumerate(pcm) if abs(s) > level]
    if not loud:
        raise SystemExit("silent clip")
    pcm = pcm[loud[0]:loud[-1] + 1]
    peak = max(abs(s) for s in pcm)
    g = PEAK / peak
    pcm = [max(-32768, min(32767, int(round(s * g)))) for s in pcm]
    return [0] * PAD + pcm + [0] * PAD


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wav", default="wav")
    ap.add_argument("--out", default="../../proj_cm55/audio")
    a = ap.parse_args()

    prompts = load_prompts()
    clips, total = [], 0
    for pid, text in prompts:
        pcm = prepare(load_wav(os.path.join(a.wav, pid + ".wav")))
        data = ima_encode(pcm)
        clips.append((pid, text, len(pcm), data))
        total += len(data)

    h = ["/* Generated by tools/audio_clips/wav2c.py - do not edit. */",
         "#ifndef AUDIO_CLIPS_H", "#define AUDIO_CLIPS_H", "",
         "#include <stdint.h>", "",
         "#define AUDIO_CLIPS_SAMPLE_RATE_HZ  (%uU)" % RATE, "",
         "typedef struct", "{",
         "    const uint8_t* data;   /* IMA ADPCM, low nibble first */",
         "    uint32_t samples;      /* number of 16-bit samples */",
         "    const char* name;", "} audio_clip_t;", "",
         "typedef enum", "{"]
    for i, (pid, text, n, data) in enumerate(clips):
        h.append("    AUDIO_CLIP_%-20s = %2d,  /* %s, %.2f s */" % (pid, i, text, n / RATE))
    h += ["    AUDIO_CLIP_COUNT", "} audio_clip_id_t;", "",
          "extern const audio_clip_t audio_clips[AUDIO_CLIP_COUNT];", "",
          "#endif /* AUDIO_CLIPS_H */", ""]

    c = ["/* Generated by tools/audio_clips/wav2c.py - do not edit.",
         " * %d clips, %d bytes of IMA ADPCM (16 kHz mono)." % (len(clips), total),
         " * Placeholder voice: offline TTS (sherpa-onnx, MeloTTS zh_en, MIT). */",
         '#include "audio_clips.h"', ""]
    for pid, text, n, data in clips:
        c.append("static const uint8_t clip_%s[%d] = {" % (pid.lower(), len(data)))
        for i in range(0, len(data), 16):
            c.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
        c += ["};", ""]
    c.append("const audio_clip_t audio_clips[AUDIO_CLIP_COUNT] =")
    c.append("{")
    for pid, text, n, data in clips:
        c.append('    { clip_%s, %uU, "%s" },' % (pid.lower(), n, pid))
    c += ["};", ""]

    with open(os.path.join(a.out, "audio_clips.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(h))
    with open(os.path.join(a.out, "audio_clips.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(c))
    print(f"{len(clips)} clips, {total} bytes ADPCM, {sum(x[2] for x in clips) / RATE:.1f} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
